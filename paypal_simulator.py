
from datetime import datetime, timezone
from uuid import uuid4


def simulate_paypal_transaction(
    amount,
    currency="USD",
    country_mismatch=False,
    new_account=False,
    unusual_activity=False,
):
    """Generate a fictional PayPal-style transaction for demonstration."""

    if amount <= 0:
        raise ValueError("Transaction amount must be greater than zero.")

    transaction_id = f"SIM-{uuid4().hex[:12].upper()}"

    return {
        "id": transaction_id,
        "source": "SIMULATED_PAYPAL",
        "mode": "DEMO_ONLY",
        "status": "SIMULATED",
        "amount": {
            "currency_code": currency,
            "value": round(float(amount), 2),
        },
        "created_at": datetime.now(timezone.utc).isoformat(),
        "risk_indicators": {
            "country_mismatch": country_mismatch,
            "new_account": new_account,
            "unusual_activity": unusual_activity,
        },
        "disclaimer": (
            "Synthetic demonstration transaction. "
            "Not generated by PayPal and not a real payment."
        ),
    }
